/* Current native contract, identical to the Mac engine. Run on mini1. */
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const assert = require("node:assert/strict");
const base = path.join(__dirname, "../src/WindowsBlocker/WebAssets");
const context = vm.createContext({console, CBNativeRulePlatform:"windows"});
for (const file of ["rule-core.js", "custom-rule-runtime.js"]) vm.runInContext(fs.readFileSync(path.join(base,file),"utf8"),context);
const R = context.MacBlockerRuntime;
const run = (id,type,data={}) => JSON.parse(R.dispatch(JSON.stringify({type,now:1234,data,targetGroupId:id})));
assert.equal(JSON.parse(R.load("a", `(on,v)=>{ on("tick", ev=>{v.state.n=(v.state.n||0)+1;v.block("steam.exe");v.log("mine",v.state.n);}); }`, '{"n":4}')).ok,true);
let result=run("a","tick");
assert.equal(result.actions[0].kind,"block");
assert.equal(result.actions[0].appId,"steam.exe");
assert.equal(JSON.parse(result.states.a).n,5);
assert.equal(result.logs[0].groupId,"a");
assert.equal(result.logs[0].message,"mine 5");
assert.equal(JSON.parse(R.load("b", '(on,v)=>{on("tick",()=>v.log(v.state.n||0))}')).ok,true);
assert.equal(run("b","tick").logs[0].message,"0");
assert.equal(JSON.parse(R.load("a", '(on)=>{throw Error("bad edit")}')).ok,false);
assert.equal(JSON.parse(run("a","tick").states.a).n,6);
R.suppress("a",true);
assert.equal(run("a","tick").actions.length,0);
R.suppress("a",false);
assert.equal(run("a","tick").actions.length,1);
R.unload("a");
assert.equal(run("a","tick").actions.length,0);
assert.equal(JSON.parse(R.load("old", '(event)=>{event.on("tickEvent","id",()=>{})}')).ok,false);
const longPath = "C:\\" + "a\\".repeat(200) + "game.exe";
assert.equal(JSON.parse(R.load("long", '(on,v)=>on("tick", ev=>v.block(ev.data.appId))')).ok,true);
assert.equal(run("long","tick",{appId:longPath}).actions[0].appId,longPath);
assert.equal(run("long","tick",{appId:"x".repeat(32768)}).actions.length,0);
console.log("PASS native raw actions, state restoration, per-group isolation, failed-edit preservation, suppression, unload, and retired API rejection");
console.log("PASS long Windows app identities are exact; overlong identities are refused without truncation");
